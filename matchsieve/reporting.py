def fmt_sample(team: dict[str,Any]) -> str:
    if not team['sample_size']: return f"### {team['team']}\nNo completed historical matches are currently stored before this fixture."
    return (f"### {team['team']} — last {team['sample_size']} available completed matches\n"
            f"- Average goals scored: {team['goals_for_avg']}\n- Average goals conceded: {team['goals_against_avg']}\n"
            f"- Average total goals per match: {team['total_goals_avg']}\n- Under 4.5: {team['under_4_5_count']}/{team['sample_size']}\n"
            f"- Matches with 5+ total goals: {team['five_plus_goals_count']}/{team['sample_size']}\n"
            f"- Both teams scored: {team['btts_count']}/{team['sample_size']}\n"
            f"- Clean sheets: {team['clean_sheets']}/{team['sample_size']}\n"
            f"- W/D/L: {team['wdl']['W']}/{team['wdl']['D']}/{team['wdl']['L']}\n")


def report_to_markdown(e: dict[str,Any], narrative: str | None=None) -> str:
    f=e['fixture']; mk=e['market']
    lines=[f"# {f['home_team']} vs {f['away_team']}","",
        f"**Competition:** {f['competition']}  ",f"**Kickoff (stored UTC):** {f['kickoff_utc']}  ",f"**Market requested:** {mk['label']}  ",
        f"**Research status:** \`{e['status']}\`  ",f"**Generated:** {e['generated_at']}  ","**Publication status:** Draft — not published", "",
        "> This is an evidence-led research summary, not a guaranteed outcome or instruction to place a bet. All figures reflect records stored in the local archive at generation time.","",
        "## The market question",mk['question'],"", "## Evidence from recent completed matches",fmt_sample(e['home_form']),"",fmt_sample(e['away_form']),""]
    if e.get("history_coverage"):
        lines += ["## Pasted history coverage"]
        for key, label in (("home_form", "Home-team form"), ("away_form", "Away-team form"), ("h2h", "Head-to-head")):
            coverage = e["history_coverage"].get(key, {})
            lines.append(f"- {label}: {coverage.get('records_found', 0)}/35 records captured; {coverage.get('status', 'unknown')}.")
    lines += ["", "## Signals that may support this market"]
    lines += [f"- {x}" for x in (e['supporting_signals'] or ["No supporting historical indicators are available."])]
    lines += ["", "## Signals against it / reasons for caution"]
    lines += [f"- {x}" for x in (e['counter_signals'] or ["No opposing signal could be computed from stored records."])]
    lines += ["", "## Head-to-head context",f"Stored completed H2H meetings found: {len(e['h2h'])}. H2H is contextual evidence only and is not the headline of this report.",""]
    if e['h2h']:
        for h in e['h2h'][:5]: lines.append(f"- {h['kickoff_utc'][:10]} — {h['home_team']} {h['home_score']}–{h['away_score']} {h['away_team']} ({h['competition']})")
    else: lines.append("- No prior H2H results are currently stored in the archive.")
    lines += ["", "## Missing / unverified information"]
    lines += [f"- {x}" for x in e['missing_information']] if e['missing_information'] else ["- No missing items identified by the current baseline checks; this does not mean every possible data source was checked."]
    if narrative:
        lines += ["", "## Plain-English research commentary (AI-assisted)", narrative, "", "**Review note:** The commentary must be checked against the structured evidence before publication."]
    lines += ["", "## Source record"]
    if e['sources']:
        for s in e['sources']:
            lines.append(f"- Source: \`{s.get('source_key')}\` | Captured: {s.get('captured_at')} | Reference: {s.get('source_ref') or 'not supplied'} | URL: {s.get('source_url') or 'not supplied'} | Quality: {s.get('quality_label')}")
            if str(s.get('source_key') or '').lower() == 'sportscore':
                lines.append('  - Attribution: Powered by SportScore — https://sportscore.com/')
    else: lines.append("- No source snapshot attached.")
    lines += ["", "## Method and limits",e['method_note'],"No final recommendation is generated by default. A human must review the evidence, current team news, line-up status and requested market before deciding whether to publish.",""]
    return "\n".join(lines)


def generate_report(fixture_id: int, market_code: str, repo: Repository | None=None, use_ollama: bool=False, reports_dir: Path | None=None) -> dict[str,Any]:
    repo=repo or Repository()
    evidence=build_evidence(repo,fixture_id,market_code)
    narrative=None; llm_used=False
    if use_ollama and OLLAMA_ENABLED:
        try:
            from .ollama_client import OllamaClient
            narrative=OllamaClient().write_commentary(evidence)
            llm_used=bool(narrative)
        except Exception as exc:
            evidence.setdefault('warnings',[]).append(f"Local AI commentary skipped: {exc}")
    markdown=report_to_markdown(evidence,narrative)
    request={"fixture_id":fixture_id,"market_code":market_code,"requested_at":utc_now(),"narrative_requested":use_ollama}
    report_id=repo.save_report(fixture_id,market_code,evidence['status'],request,evidence,markdown,llm_used)
    default_reports = (ROOT/"knowledge-base"/"reports") if repo.db_path.resolve()==__import__('matchsieve.config',fromlist=['DB_PATH']).DB_PATH.resolve() else repo.db_path.parent/"reports"
    outdir=Path(reports_dir or default_reports); outdir.mkdir(parents=True,exist_ok=True)
    f=evidence['fixture']
    raw_slug=f"{f['kickoff_utc'][:10]}_{f['home_team']}_vs_{f['away_team']}_{market_code}".lower()
    safe=re.sub(r"[^a-z0-9_-]+","-",raw_slug).strip("-")[:150] or "fixture-report"
    filepath=outdir/f"{safe}_v{_get_version(repo,fixture_id,market_code)}.md"
    filepath.write_text(markdown,encoding="utf-8")
    repo.add_knowledge_document(f"report:{report_id}",f"{f['home_team']} vs {f['away_team']} — {MARKETS[market_code]['label']}","research_report",markdown,
        tags=[f['competition'],f['home_team'],f['away_team'],market_code],sources=evidence['sources'])
    try:
        from .kb_writer import refresh_indexes
        kb_index = refresh_indexes(repo)
    except Exception as exc:
        kb_index = {"warning": str(exc)}
    out={"report_id":report_id,"path":str(filepath),"status":evidence['status'],"llm_used":llm_used,"report":evidence,"markdown":markdown,"knowledge_base":kb_index}
    return out


def _get_version(repo: Repository,fixture_id: int,market: str) -> int:
    from .db import connect
    conn=connect(repo.db_path)
    try: return int(conn.execute("SELECT MAX(report_version) FROM research_reports WHERE fixture_id=? AND market_code=?",(fixture_id,market)).fetchone()[0] or 1)
    finally: conn.close()
